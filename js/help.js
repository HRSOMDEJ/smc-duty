function openHelp(){
  var h = HELP[S.page]; if (!h) return;
  $('helpTitle').textContent = h.title;
  $('helpBody').innerHTML = '<div class="mb-3"><span class="small-muted">ผู้ใช้งาน</span><div class="fw-semibold">' + esc(h.who) + '</div></div>' +
    h.steps.map(function(s, i){ return '<div class="help-step"><div class="n">' + (i + 1) + '</div><div>' + esc(s) + '</div></div>'; }).join('') +
    (h.note ? '<div class="help-tip"><i class="bi bi-info-circle"></i> ' + esc(h.note) + '</div>' : '') +
    '<div class="mt-4 pt-3 border-top small"><div class="fw-semibold mb-1"><i class="bi bi-headset"></i> ติดต่อสอบถามการใช้งาน</div>' + contactHtml() + '</div>';
  bootstrap.Offcanvas.getOrCreateInstance($('ocHelp')).show();
}

